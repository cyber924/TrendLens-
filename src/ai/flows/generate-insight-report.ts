
'use server';
/**
 * @fileOverview Generates a in-depth report based on a user query by first
 * performing a web search and then using the results to write a report.
 *
 * - generateInsightReport - A function that handles the generation process.
 * - GenerateInsightReportInput - The input type for the function.
 * - GenerateInsightReportOutput - The return type for the function.
 */
import { ai } from '@/ai/genkit';
import { z } from 'zod';
import { searchTheWebApp } from '../tools/web-search';

export type GenerateInsightReportInput = string;
export type GenerateInsightReportOutput = string;


const ReportInputSchema = z.object({
  query: z.string().describe('The original user query.'),
  searchResults: z.string().describe('The results from the web search tool.'),
});

const ReportOutputSchema = z.object({
    report: z.string().describe('The comprehensive, Markdown-formatted report generated by the AI.'),
});

// A prompt that is only focused on writing a report from given data.
const reportWriterPrompt = ai.definePrompt({
    name: 'insightReportWriterPrompt',
    input: { schema: ReportInputSchema },
    output: { schema: ReportOutputSchema },
    prompt: `You are an elite e-commerce market analyst, consumer trend forecaster, and chief product strategist in 2026. Your task is to write an exceptionally comprehensive, deep, professional, and actionable market analysis report in Korean based on the user's query and the provided search results.

**CRITICAL GUIDELINES FOR 2026 & QUALITY:**
1. **Current Context (2026):** All insights, data projections, and consumer behaviors must reflect the current state of **2026** (e.g., advanced AI commerce, hyper-personalization, eco-friendly circular economy, omni-channel shopping shifts). Do NOT output outdated 2024 or 2025 references unless providing historical context.
2. **Depth & Detail:** Avoid brief or superficial summaries. Provide rich, structured sections with detailed market metrics, consumer pain points, specific product specs, price positioning, and concrete execution steps.
3. **Markdown Structure:** Use clear Markdown formatting with H2/H3 headers, bullet points, bold emphasis, and callout boxes.
4. **Language:** The entire report must be in fluent, professional **KOREAN**.
5. **Source Grounding:** Base your analysis on the provided **Search Results**.

**Required Report Sections:**
- **1. 2026년 시장 개요 및 핵심 요약 (Executive Summary)**
- **2. 소비자 심리 및 최신 트렌드 동향 (Consumer & Trend Dynamics)**
- **3. 주목해야 할 라이징 아이템 및 혁신 소재 (Rising Items & Innovations)**
- **4. 성공적인 상품 소싱 및 기획 전략 (Product Sourcing & Strategy)**
- **5. 가격 책정 및 마케팅 전환 블루프린트 (Pricing & Conversion Blueprint)**

---
**User's Original Query:**
"{{{query}}}"

**Search Results to Use:**
\`\`\`
{{{searchResults}}}
\`\`\`
---

Now, write the comprehensive, high-detail 2026 market intelligence report.
`,
    config: {
      safetySettings: [
        {
          category: 'HARM_CATEGORY_DANGEROUS_CONTENT',
          threshold: 'BLOCK_ONLY_HIGH',
        },
        {
          category: 'HARM_CATEGORY_HARASSMENT',
          threshold: 'BLOCK_ONLY_HIGH',
        },
      ],
    },
});


export async function generateInsightReport(
  query: GenerateInsightReportInput
): Promise<GenerateInsightReportOutput> {
  // Step 1: Always perform the web search first to gather data.
  const searchResults = await searchTheWebApp({ query });

  // Step 2: Pass the gathered data to the report-writing AI.
  const { output } = await reportWriterPrompt({
    query,
    searchResults
  });

  const reportText = output?.report;

  if (!reportText) {
    throw new Error("AI가 보고서를 생성하지 못했습니다. 다시 시도해 주세요.");
  }

  return reportText;
}
